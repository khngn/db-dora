#!/bin/bash
# dora.sh
thisDir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# app="$(basename "$thisDir")"
# ###########################################################################################
up() {(
  set -euo pipefail
  # #############################################################
  cd "$thisDir"/docker
  docker compose -f dora.docker-compose.yml up -d
)}
# ###########################################################################################
down() {(
  set -euo pipefail
  # #############################################################
  cd "$thisDir"/docker
  docker compose -f dora.docker-compose.yml down
)}
# ###########################################################################################
# ###########################################################################################
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  func="${1:-up}"
  shift
  "$func" "$@"
fi